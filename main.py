"""RFP Intelligence Platform — command line entry point.

    python main.py --bid ./Bid1                  # extraction mode (one command)
    python main.py ask "What is the submission deadline for Bid1 after all addendums?"
    python main.py search "bid bond" --bid Bid1 --doc-type rfp
    python main.py serve | ui | eval | qa-log | compare | go-no-go Bid1
"""
from __future__ import annotations

import json
import logging
import subprocess
import sys
from pathlib import Path

import typer

from settings import ROOT, cfg

app = typer.Typer(add_completion=False, help="RFP Intelligence Platform: RAG search engine + multi-agent extraction")
logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
for noisy in ("httpx", "fastembed", "urllib3"):
    logging.getLogger(noisy).setLevel(logging.WARNING)


def resolve_folder(path: Path) -> Path:
    """Accept ./Bid1, data/Bid1 or an absolute path."""
    for candidate in (path, ROOT / "data" / path.name):
        if candidate.is_dir():
            return candidate.resolve()
    raise typer.BadParameter(f"bid folder not found: {path}")


@app.callback(invoke_without_command=True)
def root(ctx: typer.Context,
         bid: Path | None = typer.Option(None, "--bid", help="Bid folder: run extraction")) -> None:
    if ctx.invoked_subcommand is None:
        if bid is None:
            typer.echo(ctx.get_help())
            raise typer.Exit()
        extract(bid)


@app.command()
def extract(folder: Path, go_no_go: bool = typer.Option(True, help="Also write the go/no-go recommendation")) -> None:
    """Extraction mode: bid folder -> outputs/<bid>.json + .md (+ trace)."""
    from agents.go_no_go_agent import evaluate_go_no_go, save_go_no_go
    from agents.graph import run_extraction
    from agents.llm import get_llm

    record, summary = run_extraction(resolve_folder(folder))
    typer.echo(json.dumps(record.validation) + f"  trace: outputs/traces/{summary['run_id']}.jsonl")
    typer.echo(f"tokens: {summary['prompt_tokens']}+{summary['completion_tokens']}  cost: ${summary['cost_usd']}  "
               f"wall: {summary['wall_ms'] / 1000:.1f}s")
    if go_no_go:
        result = evaluate_go_no_go(record, llm=get_llm())
        typer.echo(f"go/no-go: {result.decision} -> {save_go_no_go(result)}")


@app.command()
def index(folders: list[Path]) -> None:
    """Index bid folders incrementally (unchanged files are skipped)."""
    from search.index import get_index

    for f in folders:
        typer.echo(json.dumps(get_index().index_folder(resolve_folder(f))))


@app.command()
def search(query: str, bid: str | None = None, doc_type: str | None = None, addendum: int | None = None,
           top_k: int = 5, mode: str = "hybrid", rerank: bool = True) -> None:
    """Search the index; prints cited passages."""
    from search.retrieve import SearchFilters
    from search.retrieve import search as run_search

    filters = SearchFilters(bid_id=bid, doc_types=[doc_type] if doc_type else None,  # type: ignore[list-item]
                            addendum_number=addendum)
    for i, e in enumerate(run_search(query, filters=filters, top_k=top_k, mode=mode, rerank=rerank), 1):  # type: ignore[arg-type]
        score = f"{e.rerank_score:.3f}" if e.rerank_score is not None else f"{e.score:.3f}"
        typer.echo(f"\n[{i}] {score} {e.bid_id} | {e.file_name} p.{e.page_number} | {e.doc_type}\n{e.text[:500]}")


@app.command()
def ask(question: str) -> None:
    """Question-answering mode with citations."""
    from agents.qa_agent import answer_question

    a = answer_question(question)
    typer.echo(f"\n{a.answer}\n\n(answered by {a.answered_by}; bids {a.bids})")
    for c in a.citations:
        typer.echo(f"  - {c.file} p.{c.page}")


@app.command("qa-log")
def qa_log(questions: Path = ROOT / "eval" / "qa_questions.txt", out: Path = ROOT / "outputs" / "qa_log.md") -> None:
    """Answer every question in a file and write a markdown Q&A log."""
    from agents.qa_agent import answer_question

    lines = ["# Sample Q&A log", "", "Generated by `python main.py qa-log`. Each answer cites file and page.", ""]
    for i, q in enumerate([q.strip() for q in questions.read_text().splitlines() if q.strip()], 1):
        a = answer_question(q)
        cites = "; ".join(dict.fromkeys(f"{c.file} p.{c.page}" for c in a.citations)) or "—"
        lines += [f"## Q{i}. {q}", "", a.answer, "", f"*Answered by:* `{a.answered_by}` · *Bids:* {', '.join(a.bids)}"
                  f" · *Sources:* {cites} · *Trace:* `{a.run_id}`", ""]
        typer.echo(f"Q{i} done ({a.answered_by})")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    typer.echo(f"wrote {out}")


@app.command()
def compare(bids: list[str] = typer.Argument(None)) -> None:
    """Side-by-side comparison report of extracted bids (outputs/comparison.md)."""
    from agents.comparison_agent import comparison_report
    from agents.schemas import BidRecord

    out = ROOT / cfg("outputs", "dir")
    paths = [out / f"{b}.json" for b in bids] if bids else sorted(p for p in out.glob("*.json"))
    records = [BidRecord.model_validate_json(p.read_text()) for p in paths]
    if len(records) < 2:
        raise typer.BadParameter("need at least two extracted bids (run extraction first)")
    comparison_report(records)
    typer.echo(f"wrote {out / 'comparison.md'}")


@app.command("go-no-go")
def go_no_go_cmd(bid: str) -> None:
    """Go / No-Go recommendation for an extracted bid using config/company_profile.yaml."""
    from agents.go_no_go_agent import evaluate_go_no_go, save_go_no_go
    from agents.llm import get_llm
    from agents.schemas import BidRecord

    record = BidRecord.model_validate_json((ROOT / cfg("outputs", "dir") / f"{bid}.json").read_text())
    result = evaluate_go_no_go(record, llm=get_llm())
    typer.echo(f"{result.decision}: {result.explanation}\n-> {save_go_no_go(result)}")


@app.command("eval")
def run_eval(chunk_sizes: str = "") -> None:
    """Retrieval evaluation (Recall@k, MRR, nDCG) -> eval/report.md."""
    sys.argv = ["run_eval"] + (["--chunk-sizes", chunk_sizes] if chunk_sizes else [])
    from eval.run_eval import main as eval_main

    eval_main()


@app.command()
def serve(host: str = "0.0.0.0", port: int = 8000) -> None:  # noqa: S104 - container entrypoint
    """REST API (FastAPI) on http://host:port (docs at /docs)."""
    import uvicorn

    uvicorn.run("api.app:app", host=host, port=port)


@app.command()
def ui(port: int = 8501) -> None:
    """Streamlit web UI (talks to the REST API at $API_URL, default http://localhost:8000)."""
    subprocess.run([sys.executable, "-m", "streamlit", "run", str(ROOT / "ui" / "streamlit_app.py"),
                    "--server.port", str(port)], check=False)


if __name__ == "__main__":
    app()
